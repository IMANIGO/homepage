export function airportSearchQueries(place: string) {
  const code = place.trim().toUpperCase();
  if (!/^[A-Z]{3}$/.test(code)) {
    return [];
  }

  const named = AIRPORT_QUERIES[code];
  const queries = named
    ? [named, `${code} Airport`, `Flughafen ${code}`]
    : [`${code} Airport`, `Flughafen ${code}`, `${code} Aeroporto`];

  return [...new Set(queries)];
}
